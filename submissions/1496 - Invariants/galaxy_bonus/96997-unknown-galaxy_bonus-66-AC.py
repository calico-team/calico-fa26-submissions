import sys
from collections import deque

def solve(N: int, M: int, Q: int, G: list[str], start: list[tuple[int, int]], end: list[tuple[int, int]]) -> list[str]:
    component = {}
    comp_id = 0

    for r in range(N):
        for c in range(M):
            for mode in (0, 1):
                if (r, c, mode) in component:
                    continue

                tile = G[r][c]
                if tile == 'R' and mode == 0:
                    continue
                if tile == 'B' and mode == 1:
                    continue

                queue = deque([(r, c, mode)])
                component[(r, c, mode)] = comp_id

                while queue:
                    curr_r, curr_c, curr_mode = queue.popleft()

                    if G[curr_r][curr_c] == '.':
                        next_mode = 1 - curr_mode
                        if (curr_r, curr_c, next_mode) not in component:
                            component[(curr_r, curr_c, next_mode)] = comp_id
                            queue.append((curr_r, curr_c, next_mode))

                    for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                        nr, nc = curr_r + dr, curr_c + dc
                        if 0 <= nr < N and 0 <= nc < M:
                            ntile = G[nr][nc]
                            if ntile == 'R' and curr_mode == 0:
                                continue
                            if ntile == 'B' and curr_mode == 1:
                                continue
                            if (nr, nc, curr_mode) not in component:
                                component[(nr, nc, curr_mode)] = comp_id
                                queue.append((nr, nc, curr_mode))
                comp_id += 1

    results = []
    for i in range(Q):
        sr, sc = start[i]
        er, ec = end[i]

        start_state = (sr, sc, 0)

        possible = False
        if start_state in component:
            start_comp = component[start_state]
            if (er, ec, 0) in component and component[(er, ec, 0)] == start_comp:
                possible = True
            elif (er, ec, 1) in component and component[(er, ec, 1)] == start_comp:
                possible = True

        if possible:
            results.append("YES")
        else:
            results.append("NO")

    return results


def main():
    input_data = sys.stdin.read().split()
    if not input_data:
        return

    iterator = iter(input_data)
    T = int(next(iterator))
    for _ in range(T):
        N = int(next(iterator))
        M = int(next(iterator))
        Q = int(next(iterator))
        G = []
        for _ in range(N):
            G.append(next(iterator))
        start, end = [], []
        for _ in range(Q):
            start_row = int(next(iterator))
            start_col = int(next(iterator))
            end_row = int(next(iterator))
            end_col = int(next(iterator))
            start.append((start_row, start_col))
            end.append((end_row, end_col))

        for s in solve(N, M, Q, G, start, end):
            print(s)


if __name__ == '__main__':
    main()