import sys

sys.setrecursionlimit(300000)

def solve_phase1(N: int, E: list[tuple[int, int]]) -> list[int]:
    adj = [[] for _ in range(N + 1)]
    for u, v in E:
        adj[u].append(v)
        adj[v].append(u)

    parent = [0] * (N + 1)
    stack = [1]
    visited = [False] * (N + 1)
    visited[1] = True

    head = 0
    while head < len(stack):
        u = stack[head]
        head += 1
        for v in adj[u]:
            if not visited[v]:
                visited[v] = True
                parent[v] = u
                stack.append(v)

    A = [0] * N
    for i in range(2, N + 1):
        A[i - 1] = parent[i]

    xor_checksum = 0
    for i in range(1, N):
        xor_checksum ^= A[i]
    A[0] = xor_checksum

    return A


def solve_phase2(N: int, A: list[int]) -> list[tuple[int, int]]:
    if A[0] == -1:
        edges = []
        for i in range(2, N + 1):
            edges.append((i, A[i - 1]))
        return edges

    missing_idx = -1
    for i in range(1, N):
        if A[i] == -1:
            missing_idx = i
            break

    if missing_idx != -1:
        current_xor = 0
        for i in range(1, N):
            if i != missing_idx:
                current_xor ^= A[i]
        A[missing_idx] = A[0] ^ current_xor

    edges = []
    for i in range(2, N + 1):
        edges.append((i, A[i - 1]))
    return edges


def main():
    input_data = sys.stdin.read().split()
    if not input_data:
        return

    iterator = iter(input_data)
    phase = next(iterator)
    N = int(next(iterator))

    if phase == 'FIRST':
        E = []
        for _ in range(N - 1):
            u = int(next(iterator))
            v = int(next(iterator))
            E.append((u, v))
        A = solve_phase1(N, E)
        print(' '.join(map(str, A)), flush=True)
    else:
        A = []
        for _ in range(N):
            A.append(int(next(iterator)))
        for u, v in solve_phase2(N, A):
            print(f"{u} {v}", flush=True)


if __name__ == '__main__':
    main()