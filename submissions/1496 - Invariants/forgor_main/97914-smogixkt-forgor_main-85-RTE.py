import heapq
import sys

def solve_phase1(N: int, E: list[tuple[int, int]]) -> list[int]:
    adj = [[] for _ in range(N + 1)]
    degree = [0] * (N + 1)
    for u, v in E:
        adj[u].append(v)
        adj[v].append(u)
        degree[u] += 1
        degree[v] += 1

    leaves = [i for i in range(1, N + 1) if degree[i] == 1]
    heapq.heapify(leaves)

    prufer = []
    killed = [False] * (N + 1)

    for _ in range(N - 2):
        u = heapq.heappop(leaves)
        killed[u] = True
        for v in adj[u]:
            if not killed[v]:
                prufer.append(v)
                degree[v] -= 1
                if degree[v] == 1:
                    heapq.heappush(leaves, v)
                break

    A = [0] * N
    for i in range(N - 2):
        A[i] = prufer[i]

    # Keep checksum strictly within [0, 10^6] using modulo
    total_sum_mod = sum(prufer) % 1000000

    A[N - 2] = total_sum_mod
    A[N - 1] = 0  # Dummy slot to satisfy size N requirement
    return A


def solve_phase2(N: int, A: list[int]) -> list[tuple[int, int]]:
    prufer = [0] * (N - 2)

    # If a checksum slot was corrupted, the main sequence is perfectly intact
    if A[N - 1] == -1 or A[N - 2] == -1:
        for i in range(N - 2):
            prufer[i] = A[i]
    else:
        missing_idx = -1
        for i in range(N - 2):
            if A[i] == -1:
                missing_idx = i
                break

        current_sum = 0
        for i in range(N - 2):
            if i != missing_idx:
                current_sum += A[i]

        # Uniquely recover the single missing value using modulo math
        prufer_val = (A[N - 2] - current_sum) % 1000000
        for i in range(N - 2):
            if i == missing_idx:
                prufer[i] = prufer_val
            else:
                prufer[i] = A[i]

    degree = [0] * (N + 1)
    for v in prufer:
        degree[v] += 1

    leaves = [i for i in range(1, N + 1) if degree[i] == 1]
    heapq.heapify(leaves)

    edges = []
    for v in prufer:
        u = heapq.heappop(leaves)
        edges.append((u, v))
        degree[v] -= 1
        if degree[v] == 1:
            heapq.heappush(leaves, v)

    u = heapq.heappop(leaves)
    v = heapq.heappop(leaves)
    edges.append((u, v))
    return edges


def main():
    input_data = sys.stdin.read().split()
    if not input_data:
        return

    iterator = iter(input_data)
    phase = next(iterator)
    N = int(next(iterator))

    if phase == 'FIRST':
        E = []
        for _ in range(N - 1):
            u = int(next(iterator))
            v = int(next(iterator))
            E.append((u, v))
        A = solve_phase1(N, E)
        print(' '.join(map(str, A)), flush=True)
    else:
        A = []
        for _ in range(N):
            A.append(int(next(iterator)))
        for u, v in solve_phase2(N, A):
            print(f"{u} {v}", flush=True)


if __name__ == '__main__':
    main()