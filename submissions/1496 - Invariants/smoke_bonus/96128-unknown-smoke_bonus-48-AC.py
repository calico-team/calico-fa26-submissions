def solve(N, R, A):
    available_times = [0, 0]

    for t in A:
        if available_times[0] <= t:
            available_times.pop(0)
            next_ready_time = max(t, available_times[-1]) + R
            available_times.append(next_ready_time)
        else:
            return "NO"

    return "YES"


def main():
    import sys
    input_data = sys.stdin.read().split()
    if not input_data:
        return

    iterator = iter(input_data)
    T = int(next(iterator))

    for _ in range(T):
        N = int(next(iterator))
        R = int(next(iterator))
        A = [int(next(iterator)) for _ in range(N)]
        print(solve(N, R, A))


if __name__ == '__main__':
    main()