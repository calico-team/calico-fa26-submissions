import sys

def solve(N: int, K: int, L: list):
    groups = {}
    for X, Y, Z, D in L:
        s = X + Y
        if s not in groups:
            groups[s] = {'E': [], 'N': []}
        groups[s][D].append((X, Z))

    blocked_count = 0
    for s, data in groups.items():
        e_drones = data['E']
        n_drones = data['N']
        if not e_drones or not n_drones:
            continue

        for x_e, z_e in e_drones:
            for x_n, z_n in n_drones:
                t = x_n - x_e
                if 0 <= t < K:
                    if z_e < z_n:
                        blocked_count += 1
                    elif z_n < z_e:
                        blocked_count += 1

    return (N * K) - blocked_count


def main():
    input_data = sys.stdin.read().split()
    if not input_data:
        return

    iterator = iter(input_data)
    T = int(next(iterator))
    for _ in range(T):
        N = int(next(iterator))
        K = int(next(iterator))
        L = []
        for _ in range(N):
            X = int(next(iterator))
            Y = int(next(iterator))
            Z = int(next(iterator))
            D = next(iterator)
            L.append((X, Y, Z, D))

        print(solve(N, K, L))


if __name__ == '__main__':
    main()