#include <bits/stdc++.h>
using namespace std;

struct DSU
{
    vector<int> p;
    DSU(int n) : p(n, -1) {}
    
    int find(int x) { return p[x] < 0 ? x : p[x] = find(p[x]); }
    bool conn(int x, int y) { return find(x) == find(y); }

    bool unite(int x, int y)
    {
        x = find(x), y = find(y);
        if (x == y) return false;
        if (p[x] > p[y]) swap(x, y);
        p[x] += p[y]; p[y] = x;
        return true;
    }
};

const int dx[] = {-1, 1, 0, 0};
const int dy[] = {0, 0, -1, 1};

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t;
    cin >> t;

    while (t--)
    {
        int n, m, q;
        cin >> n >> m >> q;

        vector<string> grid(n);
        for (auto& x : grid) cin >> x;

        DSU dsu(2 * n * m);
        auto blue_idx = [&](int r, int c) { return r * m + c; };
        auto red_idx = [&](int r, int c) { return (n * m) + (r * m + c); };

        for (int x = 0; x < n; x++)
        {
            for (int y = 0; y < m; y++)
            {
                char cur = grid[x][y];
                if (cur == '.') dsu.unite(blue_idx(x, y), red_idx(x, y));

                for (int i = 0; i < 4; i++)
                {
                    int nx = x + dx[i], ny = y + dy[i];
                    if (nx >= 0 and nx < n and ny >= 0 and ny < m)
                    {
                        char nxt = grid[nx][ny];
                        if ((cur == '.' or cur == 'B') and (nxt == '.' or nxt == 'B'))
                        {
                            dsu.unite(blue_idx(x, y), blue_idx(nx, ny));
                        }
                        if ((cur == '.' or cur == 'R') and (nxt == '.' or nxt == 'R'))
                        {
                            dsu.unite(red_idx(x, y), red_idx(nx, ny));
                        }
                    }
                }
            }
        }

        while (q--)
        {
            int a, b, c, d;
            cin >> a >> b >> c >> d;

            int start = blue_idx(a, b);
            int end_blue = blue_idx(c, d);
            int end_red = red_idx(c, d);

            cout << ((dsu.conn(start, end_blue) or dsu.conn(start, end_red)) ? "YES\n" : "NO\n");
        }
    }
}