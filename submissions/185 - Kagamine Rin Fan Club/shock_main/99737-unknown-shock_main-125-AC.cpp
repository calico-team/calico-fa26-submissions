#include <bits/stdc++.h>
using namespace std;
using ll = long long;

struct Earthquake { int r, c, p; };

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t;
    cin >> t;

    while (t--)
    {
        int n, m, q;
        cin >> n >> m >> q;

        vector<Earthquake> eqs(q);
        for (int i = 0; i < q; i++) cin >> eqs[i].r >> eqs[i].c >> eqs[i].p;
        vector<ll> grid((ll)n * m, 0);

        vector<set<int>> cols(n);
        for (int r = 0; r < n; r++)
        {
            for (int c = 0; c < m; c++) cols[r].insert(c);
        }

        for (int i = q - 1; i >= 0; i--)
        {
            int ri = eqs[i].r; int ci = eqs[i].c;
            ll pi = eqs[i].p; ll pis = pi*pi;
            int r_mn = ri - pi; int r_mx = ri + pi;

            for (int r = r_mn; r <= r_mx; r++)
            {
                ll rd_sq = (ll) (r - ri) * (r - ri);
                ll rem = pis - rd_sq;
                if (rem < 0) continue;

                ll maxdist = (ll)sqrt(rem);
                ll c_mn = max((ll)0, ci - maxdist);
                ll c_mx = min((ll)m - 1, ci + maxdist);
                auto it = cols[r].lower_bound(c_mn);
                while (it != cols[r].end() and *it <= c_mx)
                {
                    int c = *it;
                    ll cd_sq = (ll) (c - ci) * (c - ci);
                    grid[(ll)r * m + c] = pis - (rd_sq + cd_sq) + 1;
                    it = cols[r].erase(it);
                }
            }
        }

        for (int r = 0; r < n; r++)
        {
            for (int c = 0; c < m; c++)
            {
                cout << grid[(ll)r * m + c] << " ";
            }
            cout << "\n";
        }
    }
}