#include <bits/stdc++.h>
using namespace std;
using ll = long long;

struct Drone 
{
    int x, y, z;
    bool operator<(const Drone& other) const 
    {
        if (x != other.x) return x < other.x;
        if (y != other.y) return y < other.y;
        return z < other.z;
    }
};

struct Group 
{
    vector<Drone> east; vector<Drone> north;
};

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t;
    cin >> t;
    while (t--)
    {
        int n, k;
        cin >> n >> k;
        unordered_map<ll, Group> groups;
        for (int i = 0; i < n; i++)
        {
            int x, y, z; char d;
            cin >> x >> y >> z >> d;
            ll s = (ll)x + y;
            if (d == 'E') groups[s].east.push_back({x, y, z});
            else groups[s].north.push_back({x, y, z});
        }

        ll total = 0;
        for (auto& pair : groups)
        {
            auto& east = pair.second.east;
            auto& north = pair.second.north;
            if (east.empty() or north.empty()) continue;

            sort(east.begin(), east.end());
            sort(north.begin(), north.end());

            int l(0), r(0), n_len(north.size());

            for (const auto& drone : east)
            {
                int x = drone.x;
                while (l < n_len and north[l].x < x) l++;
                if (r < l) r = l;
                while (r < n_len and north[r].x <= x + k - 1) r++;
                total += (r - l);
            }
        }
        
        ll ans = ((ll)n * k) - total;
        cout << ans << "\n";
    }
}