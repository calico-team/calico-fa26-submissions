struct implicSegtree
{
    ll lazy=0,mini=0;
    ll l,r;
    implicSegtree *left=nullptr,*right=nullptr;
    implicSegtree(ll i,ll j) : l(i), r(j)
    {
 
    }
    void extend()
    {
        ll mid=l+r>>1;
        if(l==r)
            return;
        if(left==nullptr)
            left=new implicSegtree(l,mid);
        if(right==nullptr)
            right=new implicSegtree(mid+1,r);
    }
    void propagate()
    {
        if(lazy==0)
            return;
        mini=lazy;
        if(l==r)
        {
            lazy=0;
            return;
        }
        extend();
        left->lazy=lazy;
        right->lazy=lazy;
        lazy=0;
    }
    void combine()
    {
        mini=min(left->mini,right->mini);
    }
    void update(ll queryL,ll queryR,ll x)
    {
        propagate();
        if(queryR<l || r < queryL)
        {
            return;
        }
        else if(queryL<=l && r<=queryR)
        {
            lazy=x;
            propagate();
        }
        else
        {
            extend();
            propagate();
            left->update(queryL,queryR,x);
            right->update(queryL,queryR,x);
            combine();
        }
    }
    ll query(ll queryL,ll queryR)
    {
        propagate();
        if(queryR<l || r < queryL)
        {
            return LONG_LONG_MAX;
        }
        else if(queryL<=l && r<=queryR)
        {
            return mini;
        }
        else
        {
            extend();
            propagate();
            return min(left->query(queryL,queryR),
                right->query(queryL,queryR));
        }
    }
};


