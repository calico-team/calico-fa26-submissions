//https://www.geeksforgeeks.org/kmp-algorithm-for-pattern-searching/
void constructLps(string &pat, vector<int> &lps) {

    // len stores the length of longest prefix which
    // is also a suffix for the previous index
    int len = 0;

    // lps[0] is always 0
    lps[0] = 0;

    int i = 1;
    while (i < pat.length()) {

        // If characters match, increment the size of lps
        if (pat[i] == pat[len]) {
            len++;
            lps[i] = len;
            i++;
        }

        // If there is a mismatch
        else {
            if (len != 0) {

                // Update len to the previous lps value
                // to avoid reduntant comparisons
                len = lps[len - 1];
            }
            else {

                // If no matching prefix found, set lps[i] to 0
                lps[i] = 0;
                i++;
            }
        }
    }
}

vector<int> search(string &pat, string &txt) {
    int n = txt.length();
    int m = pat.length();

    vector<int> lps(m);
    vector<int> res;

    constructLps(pat, lps);

    // Pointers i and j, for traversing
    // the text and pattern
    int i = 0;
    int j = 0;

    while (i < n) {

        // If characters match, move both pointers forward
        if (txt[i] == pat[j]) {
            i++;
            j++;

            // If the entire pattern is matched
            // store the start index in result
            if (j == m) {
                res.push_back(i - j);

                // Use LPS of previous index to
                // skip unnecessary comparisons
                j = lps[j - 1];
            }
        }

        // If there is a mismatch
        else {

            // Use lps value of previous index
            // to avoid redundant comparisons
            if (j != 0)
                j = lps[j - 1];
            else
                i++;
        }
    }
    return res;
}

struct segtree
{
  ll l,r;
  ll _sum=0,_lazy=0;
  segtree *leftchild,*rightchild;
  void propagate()
  {
    if(_lazy==0)
      return;
    else if(leftchild)
    {
      leftchild -> _lazy += _lazy;
      rightchild -> _lazy += _lazy;
    }
    _sum+=(r-l+1)*_lazy;
    _lazy=0;
  };
  void combine()
  {
    _sum=(leftchild->_sum)+(rightchild->_sum);
  };
  segtree(vll &arr): segtree(arr,1,arr.size()){};
  segtree(vll &arr,int i,int j): l(i), r(j)
  {
    if(i==j)
    {
      _sum=arr[i-1];
      leftchild = rightchild = nullptr;
    }
    else
    {
      ll mid=i+(j-i)/2;
      leftchild = new segtree(arr,i,mid);
      rightchild = new segtree(arr,mid+1,j);
      combine();
    }
  }
  void update(ll queryL,ll queryR,ll x)
  {
    propagate();
    if(queryL<=l && r<=queryR)
    {
      _lazy+=x;
      propagate();
      return;
    }
    else if(queryR<l || r<queryL)
    {
      return;
    }
    else
    {
      leftchild->update(queryL,queryR,x);
      rightchild->update(queryL,queryR,x);
      combine();
    }
  }
  ll query(ll queryL,ll queryR)
  {
    propagate();
    if(queryL<=l && r<=queryR)
    {
      return _sum;
    }
    else if(queryR<l || r<queryL)
    {
      return 0;
    }
    else
    {
      return (leftchild->query(queryL,queryR))+(rightchild->query(queryL,queryR));
    }
  }
};
