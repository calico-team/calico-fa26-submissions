vector<char> segmentedSieve(ll L, ll R) {
    // generate all primes up to sqrt(R)
    ll lim = sqrt(R);
    vector<char> mark(lim + 1, false);
    vector<ll> primes;
    for (ll i = 2; i <= lim; ++i) {
        if (!mark[i]) {
            primes.emplace_back(i);
            for (ll j = i * i; j <= lim; j += i)
                mark[j] = true;
        }
    }

    vector<char> isPrime(R - L + 1, true);
    for (ll i : primes)
        for (ll j = max(i * i, (L + i - 1) / i * i); j <= R; j += i)
            isPrime[j - L] = false;
    if (L == 1)
        isPrime[0] = false;
    return isPrime;
}

ll kadane(vll &a)
{
  ll ans = a[0], sum = 0;

  for (ll r = 0; r < a.size(); r++)
  {
      sum += a[r];
      ans = max(ans, sum);
      sum = max(sum, 0ll);
  }
  return ans;
}

vector<bool>sieve(ll n)
{
  vector<bool>ret(n+1,true);
  ret[0]=false;
  ret[1]=false;
  for(ll i=2;i<=n;i++)
  {
    if(ret[i])
    {
      for(ll j=i*i;j<=n;j+=i)
      {
        ret[j]=false;
      }
    }
  }
  return ret;
}

ll splitinv_count(vll &arr,ll l,ll r)
{
  if(l==r)
    return 0;
  ll mid=l+(r-l)/2;
  vll barr;
  vll carr;
  for(int i=l;i<=mid;i++)
    barr.push_back(arr[i]);
  for(int i=mid+1;i<=r;i++)
    carr.push_back(arr[i]);
  ll ans=0;
  ll k=l;
  int j=0;
  for(int i=0;i<barr.size();i++)
  {
    while(j<carr.size()&&barr[i]>carr[j])
    {
      arr[k]=carr[j];
      k+=1;
      j+=1;
    }
    ans+=j;
    arr[k]=barr[i];
    k+=1;
  }
  while(j<carr.size())
  {
    arr[k]=carr[j];
    k+=1;
    j+=1;
  }
  return ans;
}

ll inversion_count(vll &arr,ll l,ll r)
{
  if(l==r)
    return 0;
  ll mid=l+(r-l)/2;
  ll x,y,z;
  x=inversion_count(arr,l,mid);
  y=inversion_count(arr,mid+1,r);
  z=splitinv_count(arr,l,r);
  return x+y+z;
}

