import sys
import threading
from collections import *
from math import *
input = sys.stdin.readline
def print_flush(*args):
    sys.stdout.write(" ".join(map(str, args)) + "\n")
    sys.stdout.flush()
def solve():
    n,k = list(map(int,input().split()))
    a = str(input().strip())
    res = ['*']*n
    for i in a:
        temp = ""
        for j in range(n):
            if res[j] == '*':
                temp += i
            else:
                temp += res[j]
        print_flush(temp)
        msg = str(input().strip())
        if msg == 'CORRECT':
            break
        for j in range(n):
            if msg[j] != '_':
                res[j] = msg[j]
def main():
    t = int(input())
    for _ in range(t):
        solve()
if __name__ == "__main__":
    threading.Thread(target=main).start()
