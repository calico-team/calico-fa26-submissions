def solve():
    test_cases = int(input())

    for _ in range(test_cases):
        asks, time = map(int, input().split())
        ask_times = list(map(int, input().split()))

        smokes_ready = 2
        next_charge_time = 0
        all_good = True

        for current_time in ask_times:
            while smokes_ready < 2 and current_time >= next_charge_time:
                smokes_ready += 1
                next_charge_time += time

            if smokes_ready == 2:
                next_charge_time = 0

            if smokes_ready > 0:
                smokes_ready -= 1

                if smokes_ready == 1:
                    next_charge_time = current_time + time
            else:
                all_good = False
                break

        if all_good:
            print("YES")
        else:
            print("NO")

solve()

