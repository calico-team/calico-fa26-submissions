import sys

def solve():
    text = sys.stdin.read().split()
    if not text:
        return

    cases = int(text[0])
    pos = 1

    for _ in range(cases):
        total = int(text[pos])
        days = int(text[pos+1])
        pos += 2

        east = []
        north = []

        for _ in range(total):
            a = int(text[pos])
            q = int(text[pos+1])
            u = int(text[pos+2])
            move = text[pos+3]
            pos += 4

            if move == 'E':
                east.append((a, q, u))
            else:
                north.append((a, q, u))

        meets = {}

        for ex, ey, ez in east:
            for nx, ny, nz in north:
                if ex + ey == nx + ny:
                    time = nx - ex

                    if 0 <= time < days:
                        spot = (nx, ey, time)

                        if spot not in meets:
                            meets[spot] = set()

                        meets[spot].add(ez)
                        meets[spot].add(nz)

        rain = total * days

        for group in meets.values():
            lost = len(group) - 1
            rain -= lost

        print(rain)

solve()

