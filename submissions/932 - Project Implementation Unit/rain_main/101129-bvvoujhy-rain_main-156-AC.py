import sys
import bisect
from collections import defaultdict

def solve():
    text = sys.stdin.read().split()
    if not text:
        return

    cases = int(text[0])
    pos = 1

    for _ in range(cases):
        total = int(text[pos])
        days = int(text[pos+1])
        pos += 2

        east = []
        north = defaultdict(list)

        for _ in range(total):
            a = int(text[pos])
            q = int(text[pos+1])
            u = int(text[pos+2])
            move = text[pos+3]
            pos += 4

            if move == 'E':
                east.append((a, q, u))
            else:
                north[a + q].append((a, q, u))

        meets = defaultdict(list)

        for ex, ey, ez in east:
            key = ex + ey
            if key in north:
                north_list = north[key]
                north_list.sort(key=lambda item: item[0])

                all_nx = [item[0] for item in north_list]

                left = bisect.bisect_left(all_nx, ex)
                right = bisect.bisect_right(all_nx, ex + days - 1)

                for i in range(left, right):
                    nx, ny, nz = north_list[i]
                    time = nx - ex
                    spot = (nx, ey, time)
                    meets[spot].append(ez)
                    meets[spot].append(nz)

        rain = total * days

        for group in meets.values():
            unique_z = set(group)
            lost = len(unique_z) - 1
            rain -= lost

        print(rain)

solve()

