def solve():
    test_cases = int(input())

    for _ in range(test_cases):
        asks, time = map(int, input().split())
        ask_times = list(map(int, input().split()))

        smokes_ready = 2
        last_smoke_time = -10000
        all_good = True

        for current_time in ask_times:

            if smokes_ready < 2:
                if current_time - last_smoke_time >= time:
                    smokes_ready += 1
                    last_smoke_time = current_time

            if smokes_ready > 0:
                smokes_ready -= 1

                if smokes_ready == 1:
                    last_smoke_time = current_time

            else:
                all_good = False
                break

        if all_good:
            print("YES")
        else:
            print("NO")

solve()

