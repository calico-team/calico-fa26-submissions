t = int(input())

for _ in range(t):
    n, r = map(int, input().split())
    a = list(map(int, input().split()))

    charges = 2
    waiting = []
    ok = True

    for time in a:
        new_waiting = []
        for x in waiting:
            if x <= time:
               charges = charges + 1
            else:
                new_waiting.append(x)
        waiting = new_waiting
        if charges == 0:
              ok = False
              break
        charges = charges - 1
        if len(waiting) == 0:
           waiting.append(time + r)
        else:
           if time + r > waiting[-1] + r:
              waiting.append(time + r)
           else:
              waiting.append(waiting[-1] + r)
    if ok:
        print("Yes")
    else:
        print("No")