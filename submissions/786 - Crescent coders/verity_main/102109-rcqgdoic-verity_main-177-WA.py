import sys

def ask(s):
     sys.stdout.write(s + "\n")
     sys.stdout.flush()
     return sys.stdin.readline().strip()

def solve():
    t = int(input().script())
    for _ in range(t):
          line =  sys.stdin.readline().strip()
          while line == "":
             line = sys.stdin.readline().strip()
          N, K = map(int, line.split())

          chars = []
          while len(chars) < K:
            part = sys.stdin.readline().strip().split()
            if len(part) == 1 and len(part[0]) > 1 and len(chars) == 0:
                chars = list(part[0])
                break
            chars.extend(part)
          know = [None] * N
          solved = False

          for c in chars[:-1]:
              if all(x is not None for x in known):
                 break

              guess = "".join(known[i] if known[i] is not None else c for i in range(N))
              resp = ask(guess)

              if resp == "CORRECT":
                 solved = True
                 break

              if i in range(N):
                 if resp[i] != '_':
                     known[i] = resp[i]

              if not solved:
                 last = chars[-1]
                 for i in range(N):
                     if known[i] is None:
                        known[i] = last

                 final_guess = "".join(known)
                 resp = ask(final_guess)
    solve()