def solve(N: int, M: int, K: int, P: list[int]) -> int:
    """
    Return the maximum number of classes that can be taken across M semesters.

    N: the number of classes
    M: the number of semesters
    K: the maximum number of classes you can take per semester
    P: a prerequisite array for classes 1 to N (0 if there are no prerequisite classes)
    """
    prereqs = []
    for i in range(N + 1):
        prereqs.append([])
    for i in range(1, N + 1):
        prereqs[P[i - 1]].append(i)

    order = [0]
    for course in order:
        for c in prereqs[course]:
            order.append(c)



    chain = [0] * (N + 1)
    for course in reversed(order):
        best = 0
        for c in prereqs[course]:
            if chain[c] > best:
                best = chain[c]
        chain[course] = best + 1

    avail = []
    for c in prereqs[0]:
        avail.append((chain[c], c))


    crstaken = 0
    for sem in range(M):
        if len(avail) == 0:
            break

        avail.sort(reverse=True)
        chosen = avail[:K]
        avail = avail[K:]
        crstaken = crstaken + len(chosen)


        for h, c in chosen:
            for nxtcrs in prereqs[c]:
                avail.append((chain[nxtcrs], nxtcrs))


    return crstaken

def main():
    T = int(input())
    for _ in range(T):
        N, M, K = list(map(int, input().split()))
        P = list(map(int, input().split()))
        print(solve(N, M, K, P))

if __name__ == '__main__':
    main()