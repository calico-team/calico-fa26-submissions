import sys
from math import isqrt
def main():
  d=sys.stdin.buffer.read().split(); p=1; out=[]
  for _ in range(int(d[0])):
    n,m,q=int(d[p]), int(d[p+1]), int(d[p+2]);p+=3
    qs=d[p:p+3*q];p+=3*q
    W=m+1
    a=[0]*(n*W); nx=list(range(n*W))
    def f(x):
      r=x
      while nx[r]!=r:r=nx[r]
      while nx[x]!=r:nx[x],x=r, nx[x]
      return r
    for i in range(q-1, -1, -1):
      R,C,P=int(qs[3*i]), int(qs[3*i+1]), int(qs[3*i+2])
      for r in range(R-P, R+P+1):
        dr=(r-R)**2;w=isqrt(P*P-dr);b=r*W
        e=b+C+w;j=f(b+C-w)
        while j<=e:
          a[j]=P*P-dr-(j-b-C)**2+1
          nx[j]=j+1;j=f(j+1)
      for r in range(n):
        out.append(''.join(map(str,a[r*W:r*W+m])))
  print("\n".join(out))

main()