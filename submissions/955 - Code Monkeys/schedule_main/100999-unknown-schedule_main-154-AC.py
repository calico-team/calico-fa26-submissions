import sys, heapq

def main():
  d = sys.stdin.read().split()
  p=1
  for _ in range(int(d[0])):
    n,m,k = map(int, d[p:p+3]); p+=3
    P=[0]+ list(map(int, d[p:p+n])); p+=n

    ch=[[] for _ in range(n+1)]
    for i in range(1, n+1):
      ch[P[i]].append(i)

    order = [0]
    for u in order:
      order+=ch[u]

    h = [1]*(n+1)
    for u in reversed(order):
      if u:
        h[P[u]]=max(h[P[u]], h[u]+1)

    heap = [(-h[c], c) for c in ch[0]]
    heapq.heapify(heap)

    ans=0
    for _ in range(m):
      if not heap:
        break
      took=[heapq.heappop(heap)[1] for _ in range(min(k, len(heap)))]
      ans+=len(took)
      for u in took:
        for c in ch[u]:
          heapq.heappush(heap, (-h[c], c))

    print(ans)

main()